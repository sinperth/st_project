@st.cache_data
def load_data():
    # 텍스트 데이터를 pandas DataFrame으로 변환
    df = pd.read_csv(io.StringIO(DATA_STRING), sep='\t')
    df['일자'] = pd.to_datetime(df['일자'])
    # 분석을 위한 연도, 월 컬럼 추가
    df['연도'] = df['일자'].dt.year
    df['월'] = df['일자'].dt.month
    return df

